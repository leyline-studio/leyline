/// The bundled-translation language to try at startup (ADR 0019): the
/// primary subtag of the system locale (`fr_FR.UTF-8` → `fr`, `en-US` →
/// `en`), lowercased to match the `translations/<lang>/` directory names
/// `slint_build::with_bundled_translations` bundles from.
fn system_language() -> Option<String> {
    let locale = sys_locale::get_locale()?;
    let primary = locale.split(['-', '_']).next().unwrap_or(&locale);
    Some(primary.to_lowercase())
}

/// Never size the window below this, in logical pixels, regardless of how
/// small the screen-relative computation in [`size_window_to_screen`] comes
/// out — the UI needs at least this much room to stay usable.
const MIN_WINDOW_WIDTH: f32 = 1024.0;
const MIN_WINDOW_HEIGHT: f32 = 700.0;

/// Resizes and centers the window at roughly two thirds of the primary
/// monitor's resolution, instead of the fixed `preferred-width` /
/// `preferred-height` `studio.slint`'s `StudioWindow` declares (kept there
/// as the fallback size — see the call site in [`run`]).
///
/// The winit window backing a Slint window is created lazily once the event
/// loop starts (not at `StudioWindow::new()` time), so this only has
/// anything to act on once called from a `slint::spawn_local` future — see
/// the call site. If no winit window exists yet, or no monitor can be
/// identified (headless environment, an unsupported platform, or a
/// windowing system such as Wayland that doesn't report a primary monitor),
/// this is a no-op and the `.slint` fallback size stands unchanged.
fn size_window_to_screen(window: &StudioWindow) {
    let win = window.window();
    win.with_winit_window(|winit_window| {
        let Some(monitor) = winit_window
            .primary_monitor()
            .or_else(|| winit_window.current_monitor())
        else {
            return;
        };
        let scale = monitor.scale_factor() as f32;
        let monitor_size = monitor.size();
        let logical_width = monitor_size.width as f32 / scale;
        let logical_height = monitor_size.height as f32 / scale;
        let target_width = (logical_width * 2.0 / 3.0).max(MIN_WINDOW_WIDTH);
        let target_height = (logical_height * 2.0 / 3.0).max(MIN_WINDOW_HEIGHT);
        win.set_size(slint::LogicalSize::new(target_width, target_height));

        // Center on the monitor: convert the just-chosen logical size back
        // to physical pixels to match `monitor.size()`/`monitor.position()`,
        // which are always physical.
        let monitor_position = monitor.position();
        let target_physical_width = (target_width * scale) as i32;
        let target_physical_height = (target_height * scale) as i32;
        let x = monitor_position.x + (monitor_size.width as i32 - target_physical_width) / 2;
        let y = monitor_position.y + (monitor_size.height as i32 - target_physical_height) / 2;
        win.set_position(slint::PhysicalPosition::new(x, y));
    });
}

fn main() -> std::process::ExitCode {
    match run() {
        Ok(()) => std::process::ExitCode::SUCCESS,
        Err(message) => {
            eprintln!("error: {message}");
            std::process::ExitCode::FAILURE
        }
    }
}

/// The name given to a library created by the no-argument fallback (shown
/// in the window title and the About dialog, same field a library created
/// through `leyline-cli new` gets from its own `--name`).
const DEFAULT_LIBRARY_NAME: &str = "Leyline Library";

/// Where Studio opens a library when launched with no path argument:
/// `<Documents>/Leyline Library`, falling back to `<home>/Leyline Library`
/// when the platform (or a minimal container image) has no Documents
/// folder. Pure and taking the candidate directories as parameters — rather
/// than calling `directories::UserDirs` itself — so tests can point it at a
/// scratch `TempDir` instead of the real test runner's home directory;
/// [`default_library_dir`] is the thin wrapper that resolves the real ones.
fn default_library_root(documents_dir: Option<&Path>, home_dir: Option<&Path>) -> Option<PathBuf> {
    documents_dir
        .or(home_dir)
        .map(|base| base.join(DEFAULT_LIBRARY_NAME))
}

/// Resolves [`default_library_root`] against the real user directories.
fn default_library_dir() -> Result<PathBuf, String> {
    let user_dirs = directories::UserDirs::new()
        .ok_or_else(|| "cannot determine the user's home directory".to_owned())?;
    default_library_root(user_dirs.document_dir(), Some(user_dirs.home_dir()))
        .ok_or_else(|| "cannot determine a default library location".to_owned())
}

/// Opens the library at `root`, creating it first if this is the first time
/// (no `catalog.db` there yet) — used only for the no-argument fallback
/// location; a library path given explicitly on the command line still goes
/// through the plain [`Library::open`] below, unchanged, so an explicit
/// argument that points at a typo'd or missing directory keeps failing
/// loudly rather than silently creating a new, empty library there.
fn open_or_create_library(root: &Path) -> Result<Library, String> {
    std::fs::create_dir_all(root).map_err(|e| e.to_string())?;
    if root.join("catalog.db").is_file() {
        Library::open(root).map_err(|e| e.to_string())
    } else {
        Library::create(root, DEFAULT_LIBRARY_NAME).map_err(|e| e.to_string())
    }
}

/// Where the "Open Recent" library list is persisted: a small JSON array of
/// paths, one per user, next to other per-user app config rather than inside
/// any single library folder (a library is portable/self-contained per
/// `docs/catalog.md` §37 — it must not gain a side file recording other
/// libraries' locations).
fn recent_libraries_path() -> Result<PathBuf, String> {
    let dirs = directories::ProjectDirs::from("", "", "Leyline")
        .ok_or_else(|| "cannot determine the user's config directory".to_owned())?;
    Ok(dirs.config_dir().join("recent_libraries.json"))
}

/// Reads the recent-libraries list, tolerating a missing or corrupt file
/// (first launch, or a manually edited/truncated file) by returning an empty
/// list rather than failing Studio's startup over a non-essential feature.
fn load_recent_libraries(path: &Path) -> Vec<PathBuf> {
    let Ok(contents) = std::fs::read_to_string(path) else {
        return Vec::new();
    };
    serde_json::from_str::<Vec<String>>(&contents)
        .unwrap_or_default()
        .into_iter()
        .map(PathBuf::from)
        .collect()
}

fn save_recent_libraries(path: &Path, libraries: &[PathBuf]) -> Result<(), String> {
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    let strings: Vec<String> = libraries.iter().map(|p| p.display().to_string()).collect();
    let json = serde_json::to_string_pretty(&strings).map_err(|e| e.to_string())?;
    std::fs::write(path, json).map_err(|e| e.to_string())
}

/// Moves `opened` to the front of `existing`, de-duplicates, and caps the
/// list — pure so it's testable without touching the real config directory.
fn record_recent_library(existing: &[PathBuf], opened: &Path) -> Vec<PathBuf> {
    const MAX_RECENT: usize = 8;
    let mut updated = vec![opened.to_path_buf()];
    updated.extend(existing.iter().filter(|p| p.as_path() != opened).cloned());
    updated.truncate(MAX_RECENT);
    updated
}

fn run() -> Result<(), String> {
    // No argument: this is how a GUI shortcut launches Studio (the Windows
    // installer's Start Menu entry, the Linux AppImage, double-clicking the
    // macOS .app) — none of those attach a console, so the old
    // `Err("usage: ...")` here used to look like a silent, instant crash.
    // Fall back to a sensible per-OS default location instead; an explicit
    // `leyline-studio <library-dir>` argument (scripts, the CLI test
    // harness, an existing user's shortcut) still behaves exactly as before.
    let library = match std::env::args().nth(1) {
        Some(root) => Library::open(Path::new(&root)).map_err(|e| e.to_string())?,
        None => open_or_create_library(&default_library_dir()?)?,
    };
    let info = library.catalog().library().map_err(|e| e.to_string())?;
    let library_path = library.root().display().to_string();
    let events = library.subscribe();

    // "Open Recent" (File menu): record this library, then keep the rest of
    // the list (the ones other than the one we're opening right now) around
    // for the callback below to relaunch into. A failure to read/write this
    // file is never fatal to opening the library itself.
    let recent_path = recent_libraries_path()?;
    let recent_libraries =
        record_recent_library(&load_recent_libraries(&recent_path), library.root());
    save_recent_libraries(&recent_path, &recent_libraries)?;
    let other_recent_libraries: Vec<PathBuf> = recent_libraries
        .iter()
        .filter(|p| p.as_path() != library.root())
        .cloned()
        .collect();

    let app = Rc::new(RefCell::new(App {
        library,
        query: GridQuery::default(),
        items: Vec::new(),
        window_start: 0,
        total: 0,
        viewport: (0, 0),
        multi_selected: std::collections::BTreeSet::new(),
        develop: None,
        dev_before: None,
        dev_clipboard: None,
        dev_history: Vec::new(),
        dev_history_version: None,
        presets: Vec::new(),
        print_presets: Vec::new(),
        dev_presets: Vec::new(),
        collections: Vec::new(),
        keywords: Vec::new(),
        keyword_filter: None,
        cells: Rc::new(VecModel::default()),
        pending: VecDeque::new(),
        events,
        import_job: None,
        export_job: None,
        print_job: None,
        preview_jobs: HashSet::new(),
        tether_connected: false,
        tether_captured: 0,
        watch_active: false,
        watch_imported: 0,
        map: None,
    }));

    let window = StudioWindow::new().map_err(|e| e.to_string())?;
    // ADR 0019: system locale first, English fallback. `select_bundled_translation`
    // must run after `StudioWindow::new()` — the bundled language list is
    // registered by the generated component's constructor — and an
    // unmatched or undetectable locale simply keeps the English strings
    // `@tr(...)` is written in, so a failed lookup is not an error to surface.
    if let Some(language) = system_language() {
        let _ = slint::select_bundled_translation(&language);
    }
    window.set_library_name(SharedString::from(info.name.as_str()));
    // Surfaced in Help ▸ About Leyline (ADR 0020): the no-argument fallback
    // picks a real, disk-backed location on the user's behalf, so it must
    // stay discoverable — nobody should have to guess where their catalog
    // ended up. An explicit argument is just as worth showing here.
    window.set_library_path(SharedString::from(library_path.as_str()));
    let recent_library_names: Vec<SharedString> = other_recent_libraries
        .iter()
        .map(|p| SharedString::from(p.display().to_string()))
        .collect();
    window.set_recent_libraries(ModelRc::from(Rc::new(VecModel::from(recent_library_names))));
    // Surfaced in Help ▸ About Leyline: build-time constant from Cargo.toml's
    // `version.workspace = true`, so it stays in sync without a manual edit.
    window.set_app_version(SharedString::from(env!("CARGO_PKG_VERSION")));
    window.set_filter_label(-1);
    window.set_filter_pick(-1);
    window.set_sort_label(SharedString::from(sort_label(GridQuery::default().sort)));
    let palette: Vec<slint::Color> = (0..5)
        .filter_map(ColorLabel::from_i64)
        .map(|label| label_color(Some(label)))
        .collect();
    window.set_label_colors(ModelRc::from(Rc::new(VecModel::from(palette))));

    {
        let mut app = app.borrow_mut();
        refresh_collections(&mut app, &window)?;
        refresh_presets(&mut app, &window)?;
        reload(&mut app, &window)?;
    }

    wire_select(&app, &window);
    wire_classify(&app, &window);
    wire_settings_clipboard(&app, &window);
    wire_filters(&app, &window);
    wire_develop(&app, &window);
    wire_dialogs(&app, &window, other_recent_libraries);
    wire_collections(&app, &window);
    wire_keywords(&app, &window);
    wire_presets(&app, &window);
    wire_map(&app, &window);
    {
        // Scrolling or resizing moves the visible window: fetch the matching
        // rows from the catalog when the loaded window no longer covers it.
        let app = Rc::clone(&app);
        let handle = window.as_weak();
        window.on_viewport_moved(move |first, capacity| {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            app.viewport = (
                usize::try_from(first).unwrap_or(0),
                usize::try_from(capacity).unwrap_or(0).max(1),
            );
            let loaded = app.window_start..app.window_start + app.items.len();
            if window_is_stale(app.viewport, &loaded, app.total)
                && let Err(error) = load_window(&mut app, &window)
            {
                report_error(&window, &error);
            }
        });
    }
    // Kept alive until the event loop ends: dropping the timer stops it.
    let _events = event_pump(&app, &window);

    // The winit window (and with it, monitor info) only exists once the
    // event loop is running — see `size_window_to_screen`'s doc comment —
    // so this is scheduled as a one-shot future rather than called
    // directly here. It runs once, at the very start of `run()` below,
    // before the window is ever presented to the user.
    {
        let handle = window.as_weak();
        slint::spawn_local(async move {
            if let Some(window) = handle.upgrade() {
                size_window_to_screen(&window);
            }
        })
        .map_err(|e| e.to_string())?;
    }

    window.run().map_err(|e| e.to_string())
}

/// Starts the timer that pumps engine events into the UI — job progress,
/// finished imports and exports, freshly rendered thumbnails, added or
/// edited versions — and keeps a few thumbnail render jobs in flight off
/// the UI thread. The 30 ms interval is not a re-scan: it only drains the
/// `mpsc::Receiver` `Library::subscribe()` returns, because Slint's loop is
/// single-threaded and cannot be woken from the job threads that emit
/// events (`docs/engine-api.md` §3.2–3.3) — every UI update it triggers is
/// still driven by an event, never by the tick itself.
fn event_pump(app: &Rc<RefCell<App>>, window: &StudioWindow) -> Timer {
    let app = Rc::clone(app);
    let handle = window.as_weak();
    let timer = Timer::default();
    timer.start(TimerMode::Repeated, Duration::from_millis(30), move || {
        let Some(window) = handle.upgrade() else {
            return;
        };
        let mut app = app.borrow_mut();
        while let Ok(event) = app.events.try_recv() {
            handle_event(&mut app, &window, event);
        }
        dispatch_thumbnails(&mut app);
    });
    timer
}

/// Reacts to one engine event on the UI thread.
fn handle_event(app: &mut App, window: &StudioWindow, event: Event) {
    match event {
        Event::PreviewReady {
            asset_id,
            kind: PreviewKind::Thumbnail,
        } => {
            set_thumbnail_cell(app, asset_id);
        }
        Event::JobProgress {
            job_id,
            done,
            total,
        } => {
            let done = i32::try_from(done).unwrap_or(i32::MAX);
            let total = i32::try_from(total).unwrap_or(i32::MAX);
            if app.import_job == Some(job_id) {
                window.set_dialog_result(Tr::get(window).invoke_importing_progress(done, total));
            } else if app.export_job == Some(job_id) {
                window.set_dialog_result(Tr::get(window).invoke_exporting_progress(done, total));
            } else if app.print_job == Some(job_id) {
                window.set_dialog_result(Tr::get(window).invoke_printing_progress(done, total));
            }
        }
        Event::JobFinished { job_id, result } => {
            if app.import_job == Some(job_id) {
                app.import_job = None;
                window.set_dialog_result(match result {
                    JobResult::Import(report) => {
                        SharedString::from(import_summary(report.imported.len(), &report.skipped))
                    }
                    JobResult::Failed(reason) => {
                        Tr::get(window).invoke_import_failed(SharedString::from(reason))
                    }
                    _ => return,
                });
                // No explicit reload here: a successful import already
                // emitted `AssetsAdded` (handled below), and an import that
                // added nothing (every file skipped) leaves the grid as-is.
            } else if app.export_job == Some(job_id) {
                app.export_job = None;
                window.set_dialog_result(match result {
                    JobResult::Export(report) => SharedString::from(export_summary(&report)),
                    JobResult::Failed(reason) => {
                        Tr::get(window).invoke_export_failed(SharedString::from(reason))
                    }
                    _ => return,
                });
            } else if app.print_job == Some(job_id) {
                app.print_job = None;
                window.set_dialog_result(match result {
                    JobResult::Print(report) => SharedString::from(print_summary(&report)),
                    JobResult::Failed(reason) => {
                        Tr::get(window).invoke_print_failed(SharedString::from(reason))
                    }
                    _ => return,
                });
            } else if app.preview_jobs.remove(&job_id)
                && let JobResult::Failed(reason) = result
            {
                // Release builds have no console (`windows_subsystem =
                // "windows"`) to catch a bare `eprintln!`, so a thumbnail
                // render failure needs to reach the status line or it's
                // invisible — e.g. a missing LibRaw DLL dependency would
                // silently leave every thumbnail blank with no clue why.
                report_error(window, &reason);
            }
        }
        Event::AssetsChanged { asset_ids } => {
            // Another writer touched assets: refresh the side panel when
            // the selected photo is among them.
            let selected = window.get_selected();
            if let Some(asset) = item_at(app, selected).map(|item| item.asset_id)
                && asset_ids.contains(&asset)
            {
                show_details(app, window, selected);
            }
        }
        Event::VersionChanged { version_id } => {
            // A version's head moved — rating/label/pick, a develop commit,
            // a preset application or a reprocess (`docs/engine-api.md`
            // §3.2) — any of which can invalidate the cached thumbnail
            // (`cached_preview` follows the head revision id) or the row's
            // filter/sort position. Reload only when the version is one of
            // the loaded rows, and not while develop is open: the develop
            // view refreshes itself on every commit, the grid isn't visible,
            // and `on_exit_develop` reloads it unconditionally on the way
            // back out.
            if app.develop.is_none()
                && app.items.iter().any(|item| item.version_id == version_id)
                && let Err(error) = reload(app, window)
            {
                report_error(window, &error);
            }
        }
        Event::AssetsAdded { ref asset_ids } => {
            // A tethered shot or a watched-folder import lands here too
            // (`docs/adr/0038`, `docs/adr/0039`): both are ordinary imports
            // under the hood, so each panel's "last" line is filled in from
            // this same event rather than a dedicated one.
            if app.tether_connected
                && let Some(&asset) = asset_ids.last()
                && let Ok(details) = app.library.catalog().asset_details(asset)
            {
                app.tether_captured += 1;
                window.set_tether_captured_count(i32::try_from(app.tether_captured).unwrap_or(0));
                window.set_tether_last_captured(SharedString::from(details.filename.as_str()));
            }
            if app.watch_active
                && let Some(&asset) = asset_ids.last()
                && let Ok(details) = app.library.catalog().asset_details(asset)
            {
                app.watch_imported += 1;
                window.set_watch_imported_count(i32::try_from(app.watch_imported).unwrap_or(0));
                window.set_watch_last_imported(SharedString::from(details.filename.as_str()));
            }
            // New assets — our own import, or another writer's — can change
            // both the total count and the visible window; skip while
            // develop is open for the same reason as `VersionChanged`.
            if app.develop.is_none()
                && let Err(error) = reload(app, window)
            {
                report_error(window, &error);
            }
            // Map mode fetches pins once on entry, but tethered capture
            // and watched-folder import both add assets while it stays
            // open (`docs/adr/0038`, `docs/adr/0039`) — and a GPS-tagged
            // one belongs on the map right away, not on the next entry.
            if app.map.is_some() {
                refresh_map_pins(app, window);
            }
        }
        Event::TetherConnected => {
            app.tether_connected = true;
            app.tether_captured = 0;
            window.set_tether_connected(true);
            window.set_tether_captured_count(0);
            window.set_tether_last_captured(SharedString::default());
        }
        Event::TetherDisconnected { reason } => {
            app.tether_connected = false;
            window.set_tether_connected(false);
            window.set_tether_status(match reason {
                Some(reason) => SharedString::from(reason),
                None => SharedString::default(),
            });
        }
        Event::WatchStarted { .. } => {
            app.watch_active = true;
            app.watch_imported = 0;
            window.set_watch_active(true);
            window.set_watch_imported_count(0);
            window.set_watch_last_imported(SharedString::default());
        }
        Event::WatchStopped { reason } => {
            app.watch_active = false;
            window.set_watch_active(false);
            window.set_watch_status(match reason {
                Some(reason) => SharedString::from(reason),
                None => SharedString::default(),
            });
        }
        _ => {}
    }
}

/// Fills the grid cell of an asset with its freshly cached thumbnail.
fn set_thumbnail_cell(app: &mut App, asset: AssetId) {
    let Some(index) = app.items.iter().position(|item| item.asset_id == asset) else {
        return; // scrolled out of the loaded window meanwhile
    };
    let Ok(Some(file)) = app.library.cached_preview(asset, PreviewKind::Thumbnail) else {
        return;
    };
    let Ok(image) = slint::Image::load_from_path(&file.path) else {
        return;
    };
    if let Some(mut cell) = app.cells.row_data(index) {
        cell.thumbnail = image;
        app.cells.set_row_data(index, cell);
    }
}

/// Keeps up to [`MAX_PREVIEW_JOBS`] thumbnail renders in flight, visible
/// rows first (the pending queue is ordered that way by `load_window`).
fn dispatch_thumbnails(app: &mut App) {
    while app.preview_jobs.len() < MAX_PREVIEW_JOBS {
        let Some(index) = app.pending.pop_front() else {
            return;
        };
        let Some(asset) = app.items.get(index).map(|item| item.asset_id) else {
            continue; // the loaded window moved since this row was queued
        };
        let job = app.library.preview_async(asset, PreviewKind::Thumbnail);
        app.preview_jobs.insert(job);
    }
}

/// Fills the side panel when a cell is clicked or reached with the arrows.
fn wire_select(app: &Rc<RefCell<App>>, window: &StudioWindow) {
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_select(move |index| {
            let Some(window) = handle.upgrade() else {
                return;
            };
            // Every other path to `select` (arrow keys, double-click,
            // right-click menu actions) is a single-photo intention: it
            // always replaces whatever was multi-selected, exactly like
            // clicking a cell plainly does.
            {
                let mut app = app.borrow_mut();
                app.multi_selected.clear();
                refresh_multi_selected_cells(&app);
            }
            show_details(&mut app.borrow_mut(), &window, index);
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_cell_clicked(move |index, ctrl, shift| {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let focused = window.get_selected();
            {
                let mut app = app.borrow_mut();
                if ctrl {
                    if let Ok(index) = usize::try_from(index) {
                        // The previously lone focus joins the set it's
                        // about to be toggled within, so a first Ctrl-click
                        // right after a plain click still keeps that photo.
                        if let Ok(focused) = usize::try_from(focused) {
                            app.multi_selected.insert(focused);
                        }
                        if !app.multi_selected.remove(&index) {
                            app.multi_selected.insert(index);
                        }
                    }
                } else if shift {
                    if let (Ok(from), Ok(to)) = (usize::try_from(focused), usize::try_from(index)) {
                        let (from, to) = (from.min(to), from.max(to));
                        app.multi_selected.extend(from..=to);
                    }
                } else {
                    app.multi_selected.clear();
                }
                refresh_multi_selected_cells(&app);
            }
            window.set_selected(index);
            show_details(&mut app.borrow_mut(), &window, index);
        });
    }
}

/// Re-marks every loaded cell's `multi-selected` flag from
/// `app.multi_selected`, without refetching anything from the catalog —
/// called after every Ctrl/Shift-click.
fn refresh_multi_selected_cells(app: &App) {
    for i in 0..app.cells.row_count() {
        let Some(mut cell) = app.cells.row_data(i) else {
            continue;
        };
        let selected = app.multi_selected.contains(&(app.window_start + i));
        if cell.multi_selected != selected {
            cell.multi_selected = selected;
            app.cells.set_row_data(i, cell);
        }
    }
}

/// Applies a classement key (`0`–`9`, `p`, `x`, `u`) to the selection — every
/// multi-selected photo when there is one, otherwise just the focused photo.
/// The *toggle* direction (e.g. re-rating 3 stars clears it) is decided from
/// the focused photo's own current label/pick alone, then that one resulting
/// value is applied to the whole selection — the same "last-active item
/// decides the toggle, batch gets the result" rule Lightroom uses.
fn wire_classify(app: &Rc<RefCell<App>>, window: &StudioWindow) {
    let app = Rc::clone(app);
    let handle = window.as_weak();
    window.on_classify(move |key| {
        let Some(window) = handle.upgrade() else {
            return;
        };
        let mut app = app.borrow_mut();
        let focused = window.get_selected();
        let Some((label, pick)) = item_at(&app, focused).map(|item| (item.color_label, item.pick))
        else {
            return;
        };
        let Some(action) = classify::from_key(key.as_str(), label, pick) else {
            return;
        };
        let versions = selected_versions(&app, focused);
        if versions.is_empty() {
            return;
        }
        let applied = match action {
            Action::Rate(rating) => app.library.set_rating(&versions, rating),
            Action::Label(label) => app.library.set_color_label(&versions, label),
            Action::Flag(pick) => app.library.set_pick(&versions, pick),
        };
        if let Err(error) = applied
            .map_err(|e| e.to_string())
            .and_then(|()| reload(&mut app, &window))
        {
            report_error(&window, &error);
        }
    });
}

/// Develop settings groups copy/paste captures and applies — the same
/// default set a saved preset captures (`docs/presets.md` §3.1), Geometry
/// excluded since a crop/rotation is a per-photo judgment, not a
/// transferable style.
const CLIPBOARD_GROUPS: &[SettingsGroup] = &[
    SettingsGroup::WhiteBalance,
    SettingsGroup::Tone,
    SettingsGroup::Presence,
    SettingsGroup::LensCorrection,
    SettingsGroup::Detail,
];

/// Copy/paste develop settings between photos (distinct from named
/// presets, item 4 of the Lightroom/Darktable workflow-gap survey).
fn wire_settings_clipboard(app: &Rc<RefCell<App>>, window: &StudioWindow) {
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_copy_settings(move || {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            let Some(version) = item_at(&app, window.get_selected()).map(|item| item.version_id)
            else {
                return;
            };
            match app.library.capture_settings(version, CLIPBOARD_GROUPS) {
                Ok(settings) => {
                    app.dev_clipboard = Some(settings);
                    window.set_has_settings_clipboard(true);
                }
                Err(error) => report_error(&window, &error.to_string()),
            }
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_paste_settings(move || {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            let Some(clipboard) = app.dev_clipboard.clone() else {
                return;
            };
            let versions = selected_versions(&app, window.get_selected());
            if versions.is_empty() {
                return;
            }
            let applied = app
                .library
                .apply_settings(&clipboard, &versions, |_, _| {})
                .map_err(|e| e.to_string())
                .and_then(|report| {
                    if report.failed.is_empty() {
                        Ok(())
                    } else {
                        Err(report
                            .failed
                            .iter()
                            .map(|f| f.reason.as_str())
                            .collect::<Vec<_>>()
                            .join("; "))
                    }
                })
                .and_then(|()| reload(&mut app, &window));
            if let Err(error) = applied {
                report_error(&window, &error);
            }
            // Re-render the develop canvas too when the pasted-onto set
            // includes the photo currently open there.
            if app
                .develop
                .is_some_and(|(_, version)| versions.contains(&version))
            {
                if let Err(error) = refresh_develop(&mut app, &window) {
                    report_error(&window, &error);
                }
            }
        });
    }
}

/// Connects the filter bar: stars, label dots, pick chips, sort cycling.
fn wire_filters(app: &Rc<RefCell<App>>, window: &StudioWindow) {
    let on_error = |window: &StudioWindow, result: Result<(), String>| {
        if let Err(error) = result {
            report_error(window, &error);
        }
    };

    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_rating_filter(move |stars| {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            app.query.rating_at_least =
                classify::toggle_rating_filter(app.query.rating_at_least, stars as u8);
            window.set_filter_rating(app.query.rating_at_least.map_or(0, i32::from));
            on_error(&window, reload(&mut app, &window));
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_label_filter(move |value| {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let Some(clicked) = ColorLabel::from_i64(i64::from(value)) else {
                return;
            };
            let mut app = app.borrow_mut();
            app.query.color_label = classify::toggle_label_filter(app.query.color_label, clicked);
            window.set_filter_label(app.query.color_label.map_or(-1, |l| l.as_i64() as i32));
            on_error(&window, reload(&mut app, &window));
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_pick_filter(move |value| {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let Some(clicked) = PickState::from_i64(i64::from(value)) else {
                return;
            };
            let mut app = app.borrow_mut();
            app.query.pick = classify::toggle_pick_filter(app.query.pick, clicked);
            window.set_filter_pick(app.query.pick.map_or(-1, |p| p.as_i64() as i32));
            on_error(&window, reload(&mut app, &window));
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_search(move |text| {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            let text = text.trim();
            app.query.text = (!text.is_empty()).then(|| text.to_owned());
            on_error(&window, reload(&mut app, &window));
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_cycle_sort(move || {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            let next = SORTS
                .iter()
                .position(|(sort, _)| *sort == app.query.sort)
                .map_or(0, |i| (i + 1) % SORTS.len());
            app.query.sort = SORTS[next].0;
            window.set_sort_label(SharedString::from(SORTS[next].1));
            on_error(&window, reload(&mut app, &window));
        });
    }
}

/// Connects the develop view: entering, sliders, undo / redo, leaving.
