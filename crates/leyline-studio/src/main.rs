/// Wires the GPS map view (`docs/adr/0040-gps-map-view.md`): enter/exit,
/// importing a pack, pan/zoom, and clicking a pin to jump to that photo.
fn wire_map(app: &Rc<RefCell<App>>, window: &StudioWindow) {
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_enter_map(move || {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            // A failed pin query must not look like "no GPS photos": an
            // empty map is a legitimate state, so a silent fallback to it
            // makes a catalog problem indistinguishable from a normal
            // library.
            let (pins, status) = match app.library.map_pins() {
                Ok(pins) => (pins, None),
                Err(error) => (Vec::new(), Some(error.to_string())),
            };
            app.map = Some(new_map_state(pins, &app.library));
            let unsupported = apply_pack_info(&app, &window);
            window.set_map_status(SharedString::from(
                status.or(unsupported).unwrap_or_default(),
            ));
            window.set_map_mode(true);
            render_map(&mut app, &window);
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_exit_map(move || {
            let Some(window) = handle.upgrade() else {
                return;
            };
            app.borrow_mut().map = None;
            window.set_map_mode(false);
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_browse_camera_profile(move || {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            let Some((_, version)) = app.develop else {
                return;
            };
            let Some(path) = rfd::FileDialog::new()
                .add_filter("DCP camera profile", &["dcp"])
                .pick_file()
            else {
                return;
            };
            let referenced = (|| {
                // Importing copies the file into `Profiles/Camera/` and
                // hands back the checksum of the bytes it copied — the
                // reference is never built from a path the user typed.
                let imported = app.library.import_camera_profile(&path)?;
                let mut session = app.library.edit(version)?;
                session.set(
                    Param::CameraProfile,
                    Value::CameraProfile(Some(CameraProfile {
                        enabled: true,
                        path: imported.relative_path,
                        checksum: imported.checksum,
                    })),
                )?;
                session.commit().map(|_| ())
            })();
            if let Err(error) = referenced
                .map_err(|e| e.to_string())
                .and_then(|()| refresh_develop(&mut app, &window))
            {
                report_error(&window, &error);
            }
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_browse_map_pack(move || {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let Some(path) = rfd::FileDialog::new()
                .add_filter("MBTiles", &["mbtiles"])
                .pick_file()
            else {
                return;
            };
            let mut app = app.borrow_mut();
            match app.library.import_map_pack(&path) {
                Ok(()) => {
                    let unsupported = apply_pack_info(&app, &window);
                    window.set_map_status(SharedString::from(unsupported.unwrap_or_default()));
                    // The new pack brings its own zoom range: re-derive the
                    // whole map state rather than keep a view centered at a
                    // zoom the new pack may not cover.
                    let pins = app
                        .map
                        .as_mut()
                        .map(|state| std::mem::take(&mut state.pins))
                        .unwrap_or_default();
                    app.map = Some(new_map_state(pins, &app.library));
                    render_map(&mut app, &window);
                }
                Err(error) => window.set_map_status(SharedString::from(error.to_string())),
            }
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_map_pan(move |dx, dy| {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            if let Some(state) = &mut app.map {
                state.view.pan(f64::from(dx), f64::from(dy));
            }
            render_map(&mut app, &window);
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_map_zoom_in(move || {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            if let Some(state) = &mut app.map {
                state.view.zoom_by(1, state.min_zoom, state.max_zoom);
            }
            render_map(&mut app, &window);
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_map_zoom_out(move || {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            if let Some(state) = &mut app.map {
                state.view.zoom_by(-1, state.min_zoom, state.max_zoom);
            }
            render_map(&mut app, &window);
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_map_pin_clicked(move |index| {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            let Some(state) = &app.map else {
                return;
            };
            let Some(&(asset, version)) = state.visible_pins.get(index as usize) else {
                return;
            };
            app.map = None;
            window.set_map_mode(false);
            enter_develop_for(&mut app, &window, asset, version);
        });
    }
}

/// Builds a fresh [`MapState`] for `pins`, centered on them, with the
/// active pack's declared zoom range (a generous default when it declares
/// none, or there is no pack yet).
fn new_map_state(pins: Vec<MapPin>, library: &Library) -> MapState {
    let info = library.map_pack_info().ok().flatten();
    // MBTiles metadata is whatever the pack's author wrote: normalize it
    // into a range this renderer can honor before anything projects with
    // it (`map_view::normalize_zoom_range`).
    let (min_zoom, max_zoom) = map_view::normalize_zoom_range(
        info.as_ref().and_then(|i| i.min_zoom),
        info.as_ref().and_then(|i| i.max_zoom),
    );
    MapState {
        view: map_view::View::initial(&pins, min_zoom, max_zoom),
        pins,
        min_zoom,
        max_zoom,
        visible_pins: Vec::new(),
    }
}

/// The message to show for a pack whose tiles this renderer cannot draw,
/// or `None` when the pack is fine.
///
/// ADR 0040 chose pre-rendered *raster* tiles. A vector pack (`format =
/// pbf`, the other common MBTiles flavor) opens, reads and imports without
/// complaint — its tiles simply fail to decode as images, one by one, and
/// the map renders as flat empty fill. Saying so beats an unexplained
/// blank map.
fn unsupported_pack_message(info: Option<&leyline_sdk::TilePackInfo>) -> Option<String> {
    // A pack that declares no format at all is left alone: plenty of
    // real raster packs omit the key, and the tiles either decode or
    // they don't.
    let format = info?.format.as_deref()?.to_ascii_lowercase();
    match format.as_str() {
        "png" | "jpg" | "jpeg" | "webp" => None,
        other => Some(format!(
            "this pack stores \"{other}\" tiles; Leyline displays pre-rendered raster packs \
             (png, jpg, webp) only"
        )),
    }
}

/// Re-queries the map's pins and recomposes the canvas, keeping the
/// current pan/zoom — unlike entering map mode, which re-centers.
fn refresh_map_pins(app: &mut App, window: &StudioWindow) {
    match app.library.map_pins() {
        Ok(pins) => {
            if let Some(state) = &mut app.map {
                state.pins = pins;
            }
            render_map(app, window);
        }
        Err(error) => window.set_map_status(SharedString::from(error.to_string())),
    }
}

/// Mirrors the active pack's presence/attribution into the map panel, and
/// returns the pack's unsupported-format message if it has one so the
/// caller can decide whether it outranks whatever status it was about to
/// show.
fn apply_pack_info(app: &App, window: &StudioWindow) -> Option<String> {
    let info = app.library.map_pack_info().ok().flatten();
    window.set_map_pack_imported(info.is_some());
    let unsupported = unsupported_pack_message(info.as_ref());
    window.set_map_pack_attribution(SharedString::from(
        info.and_then(|i| i.attribution).unwrap_or_default(),
    ));
    unsupported
}

/// Recomposes the map canvas for the current pan/zoom state and updates
/// every map-view Slint property, a no-op outside map mode. Also refreshes
/// `MapState::visible_pins` so a later `map-pin-clicked(index)` resolves
/// against exactly the pins this call just put on screen.
fn render_map(app: &mut App, window: &StudioWindow) {
    if !window.get_map_pack_imported() {
        return;
    }
    let Some(state) = &app.map else {
        return;
    };
    let (canvas, projected) = map_view::render(&app.library, &state.view, &state.pins);
    window.set_map_image(map_view::to_slint_image(&canvas));
    let markers: Vec<ui::MapPinMarker> = projected
        .iter()
        .map(|pin| ui::MapPinMarker { x: pin.x, y: pin.y })
        .collect();
    window.set_map_pins(ModelRc::from(Rc::new(VecModel::from(markers))));

    let visible_pins = projected
        .iter()
        .filter_map(|pin| {
            state
                .pins
                .iter()
                .find(|p| p.version_id == pin.version_id)
                .map(|p| (p.asset_id, p.version_id))
        })
        .collect();
    if let Some(state) = &mut app.map {
        state.visible_pins = visible_pins;
    }
}

/// Finds or creates the keyword at a slash-separated path (`Nature/Birds`),
/// creating the missing levels, and returns the leaf keyword.
fn ensure_keyword_path(app: &mut App, path: &str) -> Result<KeywordId, String> {
    let tree = app.library.keyword_tree().map_err(|e| e.to_string())?;
    let (mut parent, missing) = resolve_keyword_path(&tree, path)?;
    for level in missing {
        parent = Some(
            app.library
                .create_keyword(parent, &level)
                .map_err(|e| e.to_string())?,
        );
    }
    parent.ok_or_else(|| "enter a keyword".to_owned())
}

/// Walks the keyword tree along a slash-separated path and returns the
/// deepest existing keyword plus the levels still to create beneath it.
fn resolve_keyword_path(
    tree: &[KeywordNode],
    path: &str,
) -> Result<(Option<KeywordId>, Vec<String>), String> {
    let mut parent = None;
    let mut siblings = tree;
    let mut missing = Vec::new();
    for level in path.split('/') {
        let level = level.trim();
        if level.is_empty() {
            return Err("keyword levels cannot be empty".to_owned());
        }
        if !missing.is_empty() {
            missing.push(level.to_owned());
            continue;
        }
        match siblings.iter().find(|node| node.name == level) {
            Some(node) => {
                parent = Some(node.keyword);
                siblings = &node.children;
            }
            None => missing.push(level.to_owned()),
        }
    }
    Ok((parent, missing))
}

/// The keywords of an asset as parallel `(ids, full paths)` panel rows.
fn keyword_rows(app: &App, asset: AssetId) -> Result<(Vec<KeywordId>, Vec<SharedString>), String> {
    let ids = app
        .library
        .catalog()
        .asset_keywords(asset)
        .map_err(|e| e.to_string())?;
    let tree = app.library.keyword_tree().map_err(|e| e.to_string())?;
    let mut paths = std::collections::HashMap::new();
    collect_keyword_paths(&tree, &mut paths);
    let names = ids
        .iter()
        .map(|id| SharedString::from(paths.get(id).map_or("?", String::as_str)))
        .collect();
    Ok((ids, names))
}

/// Flattens the keyword tree into an id → full path map.
fn collect_keyword_paths(
    nodes: &[KeywordNode],
    out: &mut std::collections::HashMap<KeywordId, String>,
) {
    for node in nodes {
        out.insert(node.keyword, node.path.clone());
        collect_keyword_paths(&node.children, out);
    }
}

/// Adds the selected photo's version to the active collection, or removes
/// it, then reloads the grid (membership may change what it shows).
fn collection_membership(app: &mut App, window: &StudioWindow, add: bool) {
    let Some(collection) = usize::try_from(window.get_active_collection())
        .ok()
        .and_then(|i| app.collections.get(i))
        .copied()
    else {
        report_error(window, &Tr::get(window).invoke_select_collection_first());
        return;
    };
    let Some(version) = item_at(app, window.get_selected()).map(|item| item.version_id) else {
        return;
    };
    let changed = if add {
        app.library.add_to_collection(collection, &[version])
    } else {
        app.library.remove_from_collection(collection, &[version])
    };
    if let Err(error) = changed
        .map_err(|e| e.to_string())
        .and_then(|()| reload(app, window))
    {
        report_error(window, &error);
    }
}

/// Reloads the sidebar from the catalog's collection tree.
fn refresh_collections(app: &mut App, window: &StudioWindow) -> Result<(), String> {
    let tree = app.library.collections().map_err(|e| e.to_string())?;
    let mut flat = Vec::new();
    flatten_collections(&tree, 0, &mut flat);
    app.collections = flat.iter().map(|(id, ..)| *id).collect();
    let rows: Vec<ui::CollectionRow> = flat
        .into_iter()
        .map(|(_, name, depth, smart)| ui::CollectionRow {
            name: SharedString::from(name),
            depth,
            smart,
        })
        .collect();
    window.set_collections(ModelRc::from(Rc::new(VecModel::from(rows))));
    Ok(())
}

/// Flattens the collection tree into `(id, name, depth, smart)` sidebar
/// rows, depth first, children under their parent.
fn flatten_collections(
    nodes: &[CollectionNode],
    depth: i32,
    out: &mut Vec<(CollectionId, String, i32, bool)>,
) {
    for node in nodes {
        out.push((
            node.collection,
            node.name.clone(),
            depth,
            node.collection_type == CollectionType::Smart,
        ));
        flatten_collections(&node.children, depth + 1, out);
    }
}

