/// Connects the keyword panel: tagging by path, untagging by row.
fn wire_keywords(app: &Rc<RefCell<App>>, window: &StudioWindow) {
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_add_keyword(move |path| {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            let path = path.trim().to_owned();
            if path.is_empty() {
                return;
            }
            let Some(asset) = item_at(&app, window.get_selected()).map(|item| item.asset_id) else {
                return;
            };
            let tagged = ensure_keyword_path(&mut app, &path).and_then(|keyword| {
                app.library
                    .add_keyword(&[asset], keyword)
                    .map_err(|e| e.to_string())
            });
            // Reload rather than refresh the panel alone: a text search may
            // now match (or no longer match) the tagged photo.
            if let Err(error) = tagged.and_then(|()| reload(&mut app, &window)) {
                report_error(&window, &error);
            }
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_remove_keyword(move |index| {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            let Some(asset) = item_at(&app, window.get_selected()).map(|item| item.asset_id) else {
                return;
            };
            let Some(keyword) = usize::try_from(index)
                .ok()
                .and_then(|i| app.keywords.get(i))
                .copied()
            else {
                return;
            };
            if app.keyword_filter == Some(keyword) {
                app.keyword_filter = None;
                app.query.keywords.clear();
            }
            let untagged = app
                .library
                .remove_keyword(&[asset], keyword)
                .map_err(|e| e.to_string());
            if let Err(error) = untagged.and_then(|()| reload(&mut app, &window)) {
                report_error(&window, &error);
            }
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_keyword_filter(move |index| {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            let Some(keyword) = usize::try_from(index)
                .ok()
                .and_then(|i| app.keywords.get(i))
                .copied()
            else {
                return;
            };
            app.keyword_filter = if app.keyword_filter == Some(keyword) {
                None
            } else {
                Some(keyword)
            };
            app.query.keywords = app.keyword_filter.into_iter().collect();
            window.set_filter_keyword_label(
                app.keyword_filter
                    .and_then(|k| app.keywords.iter().position(|&x| x == k))
                    .and_then(|i| window.get_detail_keywords().row_data(i))
                    .unwrap_or_default(),
            );
            if let Err(error) = reload(&mut app, &window) {
                report_error(&window, &error);
            }
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_clear_keyword_filter(move || {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            app.keyword_filter = None;
            app.query.keywords.clear();
            window.set_filter_keyword_label(SharedString::default());
            if let Err(error) = reload(&mut app, &window) {
                report_error(&window, &error);
            }
        });
    }
}

/// Connects the develop presets panel: applying, deleting, and the
/// save-as-preset dialog (`docs/presets.md` §6).
fn wire_presets(app: &Rc<RefCell<App>>, window: &StudioWindow) {
    {
        let handle = window.as_weak();
        window.on_open_preset_dialog(move || {
            let Some(window) = handle.upgrade() else {
                return;
            };
            window.set_dialog_result(SharedString::default());
            window.set_dialog(SharedString::from("preset"));
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_run_save_preset(
            move |name, white_balance, tone, presence, lens_correction, detail, geometry| {
                let Some(window) = handle.upgrade() else {
                    return;
                };
                let name = name.trim();
                if name.is_empty() {
                    window.set_dialog_result(Tr::get(&window).invoke_enter_a_name());
                    return;
                }
                let mut app = app.borrow_mut();
                let Some((_, version)) = app.develop else {
                    window.set_dialog_result(Tr::get(&window).invoke_open_photo_in_develop_first());
                    return;
                };
                let flags = [
                    (white_balance, SettingsGroup::WhiteBalance),
                    (tone, SettingsGroup::Tone),
                    (presence, SettingsGroup::Presence),
                    (lens_correction, SettingsGroup::LensCorrection),
                    (detail, SettingsGroup::Detail),
                    (geometry, SettingsGroup::Geometry),
                ];
                let groups: Vec<SettingsGroup> = flags
                    .into_iter()
                    .filter_map(|(on, group)| on.then_some(group))
                    .collect();
                if groups.is_empty() {
                    window.set_dialog_result(Tr::get(&window).invoke_pick_at_least_one_group());
                    return;
                }
                let saved = app
                    .library
                    .create_preset(name, version, &groups)
                    .map_err(|e| e.to_string())
                    .and_then(|_| refresh_presets(&mut app, &window));
                match saved {
                    Ok(()) => window.set_dialog(SharedString::default()),
                    Err(error) => {
                        window.set_dialog_result(
                            Tr::get(&window).invoke_save_failed(SharedString::from(error)),
                        );
                    }
                }
            },
        );
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_apply_preset(move |index| {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            let Some((_, version)) = app.develop else {
                return;
            };
            let Some(preset) = usize::try_from(index)
                .ok()
                .and_then(|i| app.dev_presets.get(i))
                .map(|p| p.preset)
            else {
                return;
            };
            let applied = app
                .library
                .apply_preset(preset, &[version], |_, _| {})
                .map_err(|e| e.to_string());
            match applied {
                Ok(report) => {
                    if let Some(failed) = report.failed.first() {
                        report_error(&window, &failed.reason);
                    } else if let Err(error) = refresh_develop(&mut app, &window) {
                        report_error(&window, &error);
                    }
                }
                Err(error) => report_error(&window, &error),
            }
        });
    }
    {
        let app = Rc::clone(app);
        let handle = window.as_weak();
        window.on_delete_preset(move |index| {
            let Some(window) = handle.upgrade() else {
                return;
            };
            let mut app = app.borrow_mut();
            let Some(preset) = usize::try_from(index)
                .ok()
                .and_then(|i| app.dev_presets.get(i))
                .map(|p| p.preset)
            else {
                return;
            };
            let deleted = app
                .library
                .delete_preset(preset)
                .map_err(|e| e.to_string())
                .and_then(|()| refresh_presets(&mut app, &window));
            if let Err(error) = deleted {
                report_error(&window, &error);
            }
        });
    }
}

