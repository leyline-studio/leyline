/// Surfaces a callback failure in the status line, where a GUI user can
/// see it; stderr keeps a copy for terminal logs.
/// Switches to a different library the same way Lightroom's "Open Catalog…"
/// does: spawn a fresh Studio process pointed at the new library path, then
/// quit this one. In-place switching would mean tearing down and rebuilding
/// every piece of `App` state (grid query, develop session, event
/// subscription…) that `run()` currently only ever sets up once; relaunching
/// reuses that same one-time startup path instead of duplicating it.
fn relaunch_into(window: &StudioWindow, library_root: &Path) {
    let exe = match std::env::current_exe() {
        Ok(exe) => exe,
        Err(error) => {
            report_error(window, &error.to_string());
            return;
        }
    };
    match std::process::Command::new(exe).arg(library_root).spawn() {
        Ok(_) => {
            let _ = slint::quit_event_loop();
        }
        Err(error) => report_error(window, &error.to_string()),
    }
}

fn report_error(window: &StudioWindow, message: &str) {
    eprintln!("error: {message}");
    window.set_status_line(Tr::get(window).invoke_error_prefix(SharedString::from(message)));
}

/// The window worth loading for a viewport: the visible cells plus the
/// overscan margin on each side, clamped to the grid.
fn desired_window(viewport: (usize, usize), total: u64) -> std::ops::Range<usize> {
    let (first, capacity) = viewport;
    let total = usize::try_from(total).unwrap_or(usize::MAX);
    let start = first.saturating_sub(OVERSCAN).min(total);
    let end = first
        .saturating_add(capacity)
        .saturating_add(OVERSCAN)
        .min(total);
    start..end.max(start)
}

/// True when the loaded window no longer serves the viewport: part of the
/// visible range is missing, or an edge with more rows beyond it is closer
/// than half the overscan margin.
fn window_is_stale(viewport: (usize, usize), loaded: &std::ops::Range<usize>, total: u64) -> bool {
    let (first, capacity) = viewport;
    let total = usize::try_from(total).unwrap_or(usize::MAX);
    let visible_end = first.saturating_add(capacity).min(total);
    first < loaded.start
        || visible_end > loaded.end
        || (loaded.start > 0 && first < loaded.start + OVERSCAN / 2)
        || (loaded.end < total && visible_end + OVERSCAN / 2 > loaded.end)
}

/// The grid item shown at a whole-grid index, when it is loaded.
fn item_at(app: &App, index: i32) -> Option<&GridItem> {
    usize::try_from(index)
        .ok()?
        .checked_sub(app.window_start)
        .and_then(|i| app.items.get(i))
}

/// The whole-grid indices a batch action should act on: `multi_selected`
/// when it holds more than the lone `focused` index, otherwise just
/// `focused` alone — so every existing single-photo call site keeps working
/// unchanged when nothing is multi-selected.
fn selected_indices(app: &App, focused: i32) -> Vec<usize> {
    if app.multi_selected.len() > 1 {
        return app.multi_selected.iter().copied().collect();
    }
    match usize::try_from(focused) {
        Ok(index) => vec![index],
        Err(_) => Vec::new(),
    }
}

/// The version ids of [`selected_indices`], silently dropping any index that
/// has since scrolled out of the loaded window (see [`App::multi_selected`]).
fn selected_versions(app: &App, focused: i32) -> Vec<VersionId> {
    selected_indices(app, focused)
        .into_iter()
        .filter_map(|index| {
            let signed = i32::try_from(index).ok()?;
            item_at(app, signed).map(|item| item.version_id)
        })
        .collect()
}

/// Fetches the window of rows serving the current viewport and rebuilds
/// the cell model from it (virtual scrolling: the rest of the grid only
/// exists as the scrollbar's extent).
fn load_window(app: &mut App, window: &StudioWindow) -> Result<(), String> {
    let range = desired_window(app.viewport, app.total);
    app.query.range = u32::try_from(range.start).unwrap_or(u32::MAX)
        ..u32::try_from(range.end).unwrap_or(u32::MAX);
    let items = app
        .library
        .catalog()
        .grid(&app.query)
        .map_err(|e| e.to_string())?;

    // Only thumbnails already cached are loaded here, so the window appears
    // instantly; the rest are queued and rendered by the thumbnail timer,
    // visible cells before the overscan rows above them.
    let first_visible = app.viewport.0.saturating_sub(range.start);
    let mut cells = Vec::with_capacity(items.len());
    let mut missing = Vec::new();
    for (index, item) in items.iter().enumerate() {
        let thumbnail = app
            .library
            .cached_preview(item.asset_id, PreviewKind::Thumbnail)
            .ok()
            .flatten()
            .and_then(|file| slint::Image::load_from_path(&file.path).ok());
        if thumbnail.is_none() {
            missing.push(index);
        }
        cells.push(Cell {
            thumbnail: thumbnail.unwrap_or_default(),
            filename: SharedString::from(item.filename.as_str()),
            stars: SharedString::from(format::stars(item.rating)),
            label: label_color(item.color_label),
            has_label: item.color_label.is_some(),
            multi_selected: app.multi_selected.contains(&(range.start + index)),
        });
    }
    let (visible, above): (VecDeque<usize>, VecDeque<usize>) = missing
        .into_iter()
        .partition(|&index| index >= first_visible);
    app.items = items;
    app.window_start = range.start;
    app.pending = visible.into_iter().chain(above).collect();
    app.cells = Rc::new(VecModel::from(cells));

    window.set_cells(ModelRc::from(Rc::clone(&app.cells)));
    window.set_window_start(i32::try_from(range.start).unwrap_or(i32::MAX));

    // The selection may have just scrolled into the loaded window (arrow
    // navigation past the edge): fill the side panel now that its row exists.
    let selected = window.get_selected();
    if item_at(app, selected).is_some() {
        show_details(app, window, selected);
    }
    Ok(())
}

/// Re-runs the grid query — count plus the visible window — and rebuilds
/// the cell model, keeping the current selection when the same version is
/// still in the loaded window.
fn reload(app: &mut App, window: &StudioWindow) -> Result<(), String> {
    let keep: Option<VersionId> = item_at(app, window.get_selected()).map(|item| item.version_id);

    app.total = app
        .library
        .catalog()
        .count(&app.query)
        .map_err(|e| e.to_string())?;
    let total = i32::try_from(app.total).unwrap_or(i32::MAX);
    window.set_total_cells(total);
    window.set_status_line(Tr::get(window).invoke_photo_count(total));
    load_window(app, window)?;

    let selected = keep
        .and_then(|version| app.items.iter().position(|item| item.version_id == version))
        .and_then(|i| i32::try_from(i + app.window_start).ok())
        .unwrap_or(-1);
    window.set_selected(selected);
    if selected >= 0 {
        show_details(app, window, selected);
    }
    Ok(())
}

/// Reads and formats everything the side panel shows for one grid row.
fn show_details(app: &mut App, window: &StudioWindow, index: i32) {
    let Some(asset) = item_at(app, index).map(|item| item.asset_id) else {
        return;
    };
    let details = match app.library.catalog().asset_details(asset) {
        Ok(details) => details,
        Err(error) => {
            eprintln!("error: {error}");
            return;
        }
    };
    match keyword_rows(app, asset) {
        Ok((ids, paths)) => {
            app.keywords = ids;
            window.set_detail_keywords(ModelRc::from(Rc::new(VecModel::from(paths))));
        }
        Err(error) => eprintln!("error: {error}"),
    }
    let meta = details.metadata.as_ref();
    window.set_detail_filename(SharedString::from(details.filename.as_str()));
    window.set_detail_path(SharedString::from(details.relative_path.as_str()));
    window.set_detail_capture(SharedString::from(
        details
            .capture_date
            .map_or_else(|| "—".to_owned(), format::capture_date),
    ));
    window.set_detail_dimensions(SharedString::from(format::dimensions(
        details.width,
        details.height,
    )));
    window.set_detail_file_size(SharedString::from(format::file_size(details.file_size)));
    window.set_detail_camera(SharedString::from(
        meta.and_then(|m| m.camera.as_ref()).map_or_else(
            || "—".to_owned(),
            |c| format!("{} {}", c.manufacturer, c.model),
        ),
    ));
    window.set_detail_lens(SharedString::from(
        meta.and_then(|m| m.lens.as_ref()).map_or_else(
            || "—".to_owned(),
            |l| format!("{} {}", l.manufacturer, l.model),
        ),
    ));
    window.set_detail_exposure(SharedString::from(
        meta.map_or_else(String::new, format::exposure_line),
    ));
}

/// The label shown on the sort button for a sort order.
fn sort_label(sort: Sort) -> &'static str {
    SORTS
        .iter()
        .find(|(candidate, _)| *candidate == sort)
        .map_or(SORTS[0].1, |(_, label)| label)
}

/// The dot color of a catalog color label.
fn label_color(label: Option<ColorLabel>) -> slint::Color {
    match label {
        Some(ColorLabel::Red) => slint::Color::from_rgb_u8(0xE0, 0x4F, 0x4F),
        Some(ColorLabel::Yellow) => slint::Color::from_rgb_u8(0xE0, 0xC0, 0x4F),
        Some(ColorLabel::Green) => slint::Color::from_rgb_u8(0x6F, 0xBF, 0x6F),
        Some(ColorLabel::Blue) => slint::Color::from_rgb_u8(0x5F, 0x8F, 0xDF),
        Some(ColorLabel::Purple) => slint::Color::from_rgb_u8(0xA0, 0x6F, 0xDF),
        None => slint::Color::default(),
    }
}

